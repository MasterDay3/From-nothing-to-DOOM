"""Генерує doom_data.inc: таблиці і графіку для doom.s.

    python3 tools/gen_doom_data.py > doom_data.inc

math потрібен лише для sin/cos.
"""
import math

RAYS = 64          # стовпців по 2 пікселі = вся ширина 128
VIEW_H = 56        # висота 3D-вікна; нижні 8 рядків — рядок стану
HORIZON = VIEW_H // 2
PROJ = 64          # пікселів на клітинку на відстані 1: (128/2) / tan(45°)
NDIST = 256        # індекс відстані = відстань у 1/16 клітинки
TEX = 16           # текстури 16x16
SPR = 32           # спрайт демона 32x32
MOVE = 32          # крок руху 1/8 клітинки (8.8), рух робить два таких

BAYER = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]


def byte_rows(name, values, per_line=16):
    out = [f"{name}:"]
    for i in range(0, len(values), per_line):
        out.append("    .byte " + ", ".join(f"${v & 0xFF:02X}" for v in values[i:i + per_line]))
    return out


def bits(row, on="#"):
    return int("".join("1" if c in on else "0" for c in row), 2)


def fixed(v):
    v = max(0, min(0xFFFF, round(v * 256)))
    return v & 0xFF, v >> 8


def dither2(level, y, par):
    """2 пікселі стовпця (лівий = біт 1) для яскравості level 0-16."""
    x0 = par * 2
    return (int(BAYER[y & 3][x0] < level) << 1) | int(BAYER[y & 3][x0 + 1] < level)


def wide_sprite(name, art, width_bytes):
    """'#' — світле, '+' — напівтон (шахівниця), '.' — прозоре; маска = контур 1 піксель."""
    w = width_bytes * 8
    pic, shape = [], []
    for y, row in enumerate(art):
        assert len(row) == w, (name, y, len(row))
        p = 0
        for x, c in enumerate(row):
            on = c == "#" or (c == "+" and (x + y) % 2 == 0)
            p = (p << 1) | int(on)
        pic.append(p)
        shape.append(bits(row, "#+"))
    full = (1 << w) - 1
    mask = []
    for i, r in enumerate(shape):
        m = r | (r << 1) | (r >> 1)
        if i > 0:
            m |= shape[i - 1]
        if i + 1 < len(shape):
            m |= shape[i + 1]
        mask.append(m & full)
    data = []
    shifts = [8 * (width_bytes - 1 - i) for i in range(width_bytes)]
    for p, m in zip(pic, mask):
        data += [(p >> s) & 0xFF for s in shifts]
        data += [(m >> s) & 0xFF for s in shifts]
    return [f"{name}_ROWS = {len(art)}"] + byte_rows(name, data, width_bytes * 2)


lines = ["; Згенеровано tools/gen_doom_data.py — не редагувати вручну", ""]

# рух: крок 1/8 клітинки для 256 кутів (кут 0 = схід, 64 = південь: Y карти росте вниз)
cos_v = [round(MOVE * math.cos(2 * math.pi * a / 256)) for a in range(256)]
sin_v = [round(MOVE * math.sin(2 * math.pi * a / 256)) for a in range(256)]
lines += byte_rows("cos_lo", [v & 0xFF for v in cos_v])
lines += byte_rows("cos_hi", [(v >> 8) & 0xFF for v in cos_v])
lines += byte_rows("sin_lo", [v & 0xFF for v in sin_v])
lines += byte_rows("sin_hi", [(v >> 8) & 0xFF for v in sin_v])

# DDA: |1/cos| (8.8, до $7FFF) і |cos| (0-255); для sin береться кут - 64
dd_lo, dd_hi, acos = [], [], []
for a in range(256):
    c = abs(math.cos(2 * math.pi * a / 256))
    d = 0x7FFF if c < 1e-6 else min(0x7FFF, round(256 / c))
    dd_lo.append(d & 0xFF)
    dd_hi.append(d >> 8)
    acos.append(min(255, round(256 * c)))
lines += byte_rows("dd_lo", dd_lo)
lines += byte_rows("dd_hi", dd_hi)
lines += byte_rows("acos", acos)

# корекція "риб'ячого ока": промінь c відхилений на (c - 32) кути
lines += byte_rows("fish", [min(255, round(256 * math.cos(2 * math.pi * (c - RAYS // 2) / 256)))
                            for c in range(RAYS)])

# для кожної відстані (1/16 клітинки): стіна, текстура, освітлення, демон
top, bot, vs_lo, vs_hi, v0_lo, v0_hi, light = [], [], [], [], [], [], []
stop, svs_lo, svs_hi, sv0_lo, sv0_hi = [], [], [], [], []
for i in range(NDIST):
    dist = max(i, 1) / 16
    h = PROJ / dist
    ut = HORIZON - h / 2
    ub = HORIZON + h / 2
    t = max(0, round(ut))
    b = min(VIEW_H, round(ub))
    top.append(t)
    bot.append(b)
    vstep = TEX / h
    lo, hi = fixed(vstep)
    vs_lo.append(lo)
    vs_hi.append(hi)
    lo, hi = fixed((t - ut) * vstep)
    v0_lo.append(lo)
    v0_hi.append(hi)
    light.append(max(2, min(16, round(17 - dist * 2.2))))

    dh = h * 0.8                            # демон трохи нижчий за стіну
    st = ub - dh
    s = max(1, round(st))
    stop.append(s)
    sstep = SPR / dh
    lo, hi = fixed(sstep)
    svs_lo.append(lo)
    svs_hi.append(hi)
    lo, hi = fixed(max(0, s - st) * sstep)
    sv0_lo.append(lo)
    sv0_hi.append(hi)

for name, vals in (("top_lut", top), ("bot_lut", bot), ("vstep_lo", vs_lo), ("vstep_hi", vs_hi),
                   ("v0_lo", v0_lo), ("v0_hi", v0_hi), ("light_lut", light),
                   ("spr_top_lut", stop), ("svstep_lo", svs_lo), ("svstep_hi", svs_hi),
                   ("sv0_lo", sv0_lo), ("sv0_hi", sv0_hi)):
    lines += byte_rows(name, vals)

# дизеринг: dith[L*8 + (y&3)*2 + парність стовпця]
lines += byte_rows("dith", [dither2(lev, y, par) for lev in range(17) for y in range(4) for par in range(2)])

# фон цілими байтами: у байті 4 стовпці, візерунок однаковий для всіх байтів рядка
def bg_level(y):
    return 0 if y < HORIZON else round((y - HORIZON) * 6 / (VIEW_H - HORIZON))


lines += byte_rows("bgbyte", [sum(int(BAYER[y & 3][x & 3] < bg_level(y)) << (7 - x) for x in range(8))
                              for y in range(VIEW_H)])

# квадрати для множення: a*b = f(a+b) - f(|a-b|), f(x) = x*x/4 (x до 510)
sq = [x * x // 4 for x in range(512)]
lines += byte_rows("sqlo0", [v & 0xFF for v in sq[:256]])
lines += byte_rows("sqhi0", [v >> 8 for v in sq[:256]])
lines += byte_rows("sqlo1", [v & 0xFF for v in sq[256:]])
lines += byte_rows("sqhi1", [v >> 8 for v in sq[256:]])

# 2 біти стовпця k (0-3) у байті
lines += byte_rows("expand", [v << (6 - 2 * k) for k in range(4) for v in range(4)])

